def width(text, scale):
    return sum((3 if ch == " " else 6) * scale for ch in text) - scale

def pixels(text, x, y, scale, fill, shadow=None, dx=None):
    """SVG path elements for `text` at (x, y) top-left; optional drop shadow."""
    def path(ox, oy, color):
        d = []
        cx = x + ox
        for ch in text.upper():
            if ch == " ":
                cx += 3 * scale
                continue
            g = G.get(ch, G["-"])
            for r, row in enumerate(g):
                c = 0
                while c < 5:
                    if row[c] == "#":
                        s = c
                        while c < 5 and row[c] == "#":
                            c += 1
                        d.append(f"M{cx + s*scale} {y + oy + r*scale}h{(c-s)*scale}v{scale}h-{(c-s)*scale}z")
                    else:
                        c += 1
            cx += 6 * scale
        return f'<path fill="{color}" d="{"".join(d)}"/>'
    out = ""
    if shadow:
        sh = dx if dx is not None else max(1, scale // 2)
        out += path(sh, sh, shadow)
    return out + path(0, 0, fill)
